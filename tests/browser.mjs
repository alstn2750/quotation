import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const url = process.env.FOLIO_TEST_URL || 'http://127.0.0.1:3100';
try {
  await page.goto(url);
  await page.locator('.hero').waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: '/tmp/folio-desktop.png', fullPage: true });
  assert.equal(await page.locator('.documents-table tbody tr').count(), 5);
  await page.locator('[data-action="create"]').first().click();
  await page.locator('[name="title"]').fill('브라우저 테스트 제안서');
  await page.locator('[name="client"]').fill('테스트 고객사');
  await page.locator('[name="brief"]').fill('새 브랜드의 웹사이트 제작. 모바일 대응 및 관리자 화면이 필요합니다.');
  await page.locator('[name="budget"]').fill('12500000');
  await page.locator('#create-form button[type="submit"]').click();
  await page.locator('.editor-layout').waitFor();
  await page.locator('[data-action="save"]').click();
  await page.getByText('모든 변경사항 저장됨', { exact: true }).waitFor();
  await page.locator('[data-editor-tab="quote"]').click();
  await page.locator('[data-item="0"][data-part="quantity"]').fill('2');
  await page.locator('[data-item="0"][data-part="price"]').fill('1000000');
  const expected = (2000000 + 6250000 + 2500000) * 1.1;
  assert.ok((await page.locator('#editor-totals').textContent()).includes(expected.toLocaleString('ko-KR')));
  await page.locator('[data-action="add-item"]').click();
  assert.equal(await page.locator('.quote-item').count(), 4);
  await page.locator('[data-remove-item="3"]').click();
  await page.locator('[data-action="save"]').click();
  await page.getByText('모든 변경사항 저장됨', { exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/folio-editor.png', fullPage: true });
  await page.pdf({ path: '/tmp/folio-proposal.pdf', format: 'A4', printBackground: true });
  await page.locator('[data-nav="documents"]').first().click();
  await page.locator('#document-search').fill('브라우저 테스트');
  assert.equal(await page.locator('.documents-table tbody tr').count(), 1);
  await page.reload();
  await page.locator('.hero').waitFor();
  assert.ok((await page.locator('.documents-table').textContent()).includes('브라우저 테스트 제안서'));
  await page.locator('[data-nav="clients"]').click();
  await page.locator('[data-action="add-client"]').click();
  await page.locator('[name="name"]').fill('새로운 클라이언트');
  await page.locator('[name="email"]').fill('new@example.com');
  await page.locator('#client-form button[type="submit"]').click();
  await page.getByRole('heading', { name: '새로운 클라이언트' }).waitFor();
  await page.locator('[data-nav="templates"]').first().click();
  await page.locator('[data-category="웹 · 앱 개발"]').click();
  assert.equal(await page.locator('.template-card').count(), 1);
  await page.locator('[data-nav="dashboard"]').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(350);
  await page.screenshot({ path: '/tmp/folio-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('.mobile-menu').click();
  await page.locator('[data-nav="quotes"]').click();
  await page.locator('[data-open]').first().click();
  await page.locator('[data-action="preview"]').click();
  await page.screenshot({ path: '/tmp/folio-mobile-preview.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: create, edit, quote calculation, save, reload, client, filters, responsive layout, PDF.');
} finally { await browser.close(); }
